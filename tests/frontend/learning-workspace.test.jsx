test('source-linked practice submits response and opens review evidence', async () => {
  api.knowledgePractice.mockResolvedValue({ id: 'practice', prompt: 'Water _____', note: 'Hatırlama pratiği' })
  api.knowledgeGrade.mockResolvedValue({ feedback: 'Kaynağı tekrar incele.', expected: 'evaporates', source: evidence })
  const user = userEvent.setup(); render(<LearningWorkspace courseId="course" />)
  await screen.findByRole('heading', { name: 'Physics' })
  await user.type(screen.getByLabelText('Ders kaynaklarına sorun'), 'Water?')
  await user.click(screen.getByRole('button', { name: 'Derse sor', exact: true }))
  await user.click(await screen.findByRole('button', { name: 'Bu kaynakla pratik yap' }))
  await user.type(await screen.findByLabelText('Eksik ifade'), 'wrong')
  await user.click(screen.getByRole('button', { name: 'Yanıtı kontrol et' }))
  expect(await screen.findByText('Kaynağı tekrar incele.')).toBeVisible()
  expect(api.knowledgeGrade).toHaveBeenCalledWith('course', 'practice', 'wrong')
  await user.click(screen.getByRole('button', { name: 'İlgili kaynağa dön' }))
  expect(api.knowledgeSource).toHaveBeenCalledWith('course', m.id, evidence.id)
})
